//! Exact text of a column for edit snapshots and their guards.
//!
//! `Dialect::SqlServer.text_of` is `CONVERT(NVARCHAR(MAX), col)`, whose
//! default style drops precision for `float`/`real` (6 digits), `money`
//! (2 decimals) and `datetime` (minutes), turns binary into garbage and
//! rejects `image` and CLR types. Snapshots and guards therefore use a form
//! per type: the guard SQL `openrows-sql` generates is rewritten here for
//! the target table's column types, so both sides compare the same text.

use openrows_sql::Dialect;

use crate::ddl::definition::quote;

/// The exact text of `[column]` of system type `base_type`.
pub(crate) fn exact_text(quoted: &str, base_type: &str) -> String {
    match base_type {
        "datetime" => format!("CONVERT(NVARCHAR(MAX), {quoted}, 121)"),
        "smalldatetime" => format!("CONVERT(NVARCHAR(MAX), {quoted}, 120)"),
        // .NET round-trip format: the shortest text that reads back exactly.
        "float" | "real" => format!("FORMAT({quoted}, 'R')"),
        "money" | "smallmoney" => format!("CONVERT(NVARCHAR(MAX), {quoted}, 2)"),
        "binary" | "varbinary" | "timestamp" => format!("CONVERT(NVARCHAR(MAX), {quoted}, 1)"),
        "image" | "geography" | "geometry" | "hierarchyid" => {
            format!("CONVERT(NVARCHAR(MAX), CONVERT(VARBINARY(MAX), {quoted}), 1)")
        }
        // The grid shows UUIDs in lower case.
        "uniqueidentifier" => format!("LOWER(CONVERT(NVARCHAR(36), {quoted}))"),
        _ => Dialect::SqlServer.text_of(quoted),
    }
}

/// `sql` with each generic text form of a listed column replaced by its
/// exact form; `columns` are `(name, system type)`.
pub(crate) fn exact_guards(sql: &str, columns: &[(String, String)]) -> String {
    let mut out = sql.to_owned();
    for (name, base_type) in columns {
        let quoted = quote(name);
        let generic = Dialect::SqlServer.text_of(&quoted);
        let exact = exact_text(&quoted, base_type);
        if generic != exact {
            out = out.replace(&generic, &exact);
        }
    }
    out
}

/// The `[schema].[table]` an `UPDATE`, `DELETE FROM` or `INSERT INTO`
/// statement generated by `openrows-sql` targets.
pub(crate) fn target_of(sql: &str) -> Option<(String, String)> {
    let rest = ["UPDATE ", "DELETE FROM ", "INSERT INTO "]
        .iter()
        .find_map(|head| sql.strip_prefix(head))?;
    let (schema, rest) = bracketed(rest)?;
    let (table, _) = bracketed(rest.strip_prefix('.')?)?;
    Some((schema, table))
}

/// A leading `[…]` name (`]]` unescaped) and the text after it.
fn bracketed(text: &str) -> Option<(String, &str)> {
    let body = text.strip_prefix('[')?;
    let mut name = String::new();
    let mut index = 0;
    let bytes = body.as_bytes();
    while index < bytes.len() {
        if bytes[index] == b']' {
            if bytes.get(index + 1) == Some(&b']') {
                name.push(']');
                index += 2;
                continue;
            }
            return Some((name, body.get(index + 1..)?));
        }
        let character = body.get(index..)?.chars().next()?;
        name.push(character);
        index += character.len_utf8();
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn guards_use_exact_forms_per_type() {
        let sql = "(CONVERT(VARBINARY(MAX), CONVERT(NVARCHAR(MAX), [f])) = CONVERT(VARBINARY(MAX), @P2) \
                   OR ([f] IS NULL AND @P2 IS NULL))";
        let columns = [
            ("f".to_owned(), "float".to_owned()),
            ("n".to_owned(), "int".to_owned()),
        ];
        let exact = exact_guards(
            &format!("UPDATE [dbo].[t] SET [n] = @P1 WHERE {sql}"),
            &columns,
        );
        assert!(exact.contains("CONVERT(VARBINARY(MAX), FORMAT([f], 'R'))"));
        assert!(!exact.contains("CONVERT(NVARCHAR(MAX), [f])"));
        assert_eq!(
            exact_text("[d]", "datetime"),
            "CONVERT(NVARCHAR(MAX), [d], 121)"
        );
        assert_eq!(exact_text("[x]", "xml"), "CONVERT(NVARCHAR(MAX), [x])");
    }

    #[test]
    fn targets_are_read_from_generated_statements() {
        assert_eq!(
            target_of("UPDATE [dbo].[or]]ders] SET [a] = @P1"),
            Some(("dbo".to_owned(), "or]ders".to_owned()))
        );
        assert_eq!(
            target_of("INSERT INTO [s].[t] DEFAULT VALUES"),
            Some(("s".to_owned(), "t".to_owned()))
        );
        assert_eq!(target_of("SELECT 1"), None);
        assert_eq!(target_of("DELETE FROM [s]"), None);
    }
}

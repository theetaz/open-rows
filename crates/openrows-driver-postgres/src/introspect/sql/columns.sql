-- Columns of one table-like relation in ordinal order. `{schema}` and
-- `{name}` are replaced with quoted literals.
-- Columns: name, formatted type, nullable, default or identity, comment,
-- primary-key member.
SELECT a.attname,
       pg_catalog.format_type(a.atttypid, a.atttypmod),
       NOT a.attnotnull,
       CASE a.attidentity
           WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY'
           WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY'
           ELSE pg_catalog.pg_get_expr(d.adbin, d.adrelid)
       END,
       pg_catalog.col_description(c.oid, a.attnum),
       EXISTS (SELECT 1
               FROM pg_catalog.pg_index AS x
               WHERE x.indrelid = c.oid
                 AND x.indisprimary
                 AND a.attnum = ANY (x.indkey))
FROM pg_catalog.pg_attribute AS a
JOIN pg_catalog.pg_class AS c ON c.oid = a.attrelid
JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace
LEFT JOIN pg_catalog.pg_attrdef AS d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE n.nspname = {schema}
  AND c.relname = {name}
  AND c.relkind IN ('r', 'p', 'v', 'm', 'f')
  AND a.attnum > 0
  AND NOT a.attisdropped
ORDER BY a.attnum

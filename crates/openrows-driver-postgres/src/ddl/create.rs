//! A table's definition rebuilt from the catalog (`PostgreSQL` has no single
//! built-in for tables): `CREATE TABLE` with columns, defaults, `NOT NULL`
//! and constraints, then indexes that do not back a constraint, comments and
//! triggers. Views print their stored query.
use super::{AlterError, quote, relation, text};
use openrows_driver_api::schema::{ColumnDetail, Generated, RelationKind, TableDetail, TableInfo};
use std::fmt::Write as _;

const HEADER: &str = "-- Table Definition\n";
const INDENT: &str = "    ";

/// The definition of `schema`.`table`, or a comment when it does not exist.
///
/// # Errors
/// [`AlterError::InvalidName`] for names that cannot be quoted (empty or NUL).
pub fn create_table_sql(
    schema: &str,
    table: &str,
    detail: &TableDetail,
) -> Result<String, AlterError> {
    let Some(info) = &detail.info else {
        return Ok(format!("-- {schema}.{table} was not found\n"));
    };
    let name = relation(schema, table)?;
    let mut sql = HEADER.to_owned();
    if let Some(query) = &info.view_definition {
        let _ = write!(
            sql,
            "{} {name} AS\n{};\n",
            view_keyword(info),
            trim_query(query)
        );
    } else {
        sql.push_str(&table_body(&name, info, detail)?);
    }
    let rest = [
        indexes(detail),
        comments(&name, info, &detail.columns)?,
        triggers(detail),
    ];
    for section in rest.iter().filter(|section| !section.is_empty()) {
        sql.push('\n');
        sql.push_str(section);
    }
    Ok(sql)
}

fn view_keyword(info: &TableInfo) -> &'static str {
    if info.kind == RelationKind::MaterializedView {
        "CREATE MATERIALIZED VIEW"
    } else {
        "CREATE VIEW"
    }
}

fn trim_query(query: &str) -> &str {
    query.trim().trim_end_matches(';').trim_end()
}

fn table_body(name: &str, info: &TableInfo, detail: &TableDetail) -> Result<String, AlterError> {
    let mut lines = detail
        .columns
        .iter()
        .map(column_line)
        .collect::<Result<Vec<_>, _>>()?;
    for constraint in &detail.constraints {
        lines.push(format!(
            "CONSTRAINT {} {}",
            quote(&constraint.name)?,
            constraint.definition
        ));
    }
    let keyword = if info.kind == RelationKind::ForeignTable {
        "CREATE FOREIGN TABLE"
    } else {
        "CREATE TABLE"
    };
    let mut sql = if lines.is_empty() {
        format!("{keyword} {name} ()")
    } else {
        let body = lines
            .iter()
            .map(|line| format!("{INDENT}{line}"))
            .collect::<Vec<_>>()
            .join(",\n");
        format!("{keyword} {name} (\n{body}\n)")
    };
    if let Some(key) = &info.partition_key {
        let _ = write!(sql, " PARTITION BY {key}");
    }
    sql.push_str(";\n");
    Ok(sql)
}

fn column_line(column: &ColumnDetail) -> Result<String, AlterError> {
    let mut line = format!("{} {}", quote(&column.name)?, column.data_type);
    if !column.nullable
        && !matches!(
            column.generated,
            Generated::IdentityAlways | Generated::IdentityByDefault
        )
    {
        line.push_str(" NOT NULL");
    }
    match (column.generated, &column.default) {
        (Generated::IdentityAlways, _) => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
        (Generated::IdentityByDefault, _) => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
        (Generated::Stored, Some(expression)) => {
            let _ = write!(line, " GENERATED ALWAYS AS ({expression}) STORED");
        }
        (_, Some(expression)) => {
            let _ = write!(line, " DEFAULT {expression}");
        }
        (_, None) => {}
    }
    Ok(line)
}

fn indexes(detail: &TableDetail) -> String {
    detail
        .indexes
        .iter()
        .filter(|index| !index.constraint)
        .fold(String::new(), |mut sql, index| {
            let _ = writeln!(sql, "{};", index.definition);
            sql
        })
}

fn comments(name: &str, info: &TableInfo, columns: &[ColumnDetail]) -> Result<String, AlterError> {
    let mut sql = String::new();
    if let Some(comment) = &info.comment {
        let target = match info.kind {
            RelationKind::View => "VIEW",
            RelationKind::MaterializedView => "MATERIALIZED VIEW",
            RelationKind::ForeignTable => "FOREIGN TABLE",
            RelationKind::Table | RelationKind::PartitionedTable => "TABLE",
        };
        let _ = writeln!(
            sql,
            "COMMENT ON {target} {name} IS {};",
            text(Some(comment))?
        );
    }
    for column in columns {
        if let Some(comment) = &column.comment {
            let _ = writeln!(
                sql,
                "COMMENT ON COLUMN {name}.{} IS {};",
                quote(&column.name)?,
                text(Some(comment))?
            );
        }
    }
    Ok(sql)
}

fn triggers(detail: &TableDetail) -> String {
    detail
        .triggers
        .iter()
        .fold(String::new(), |mut sql, trigger| {
            let _ = writeln!(sql, "{};", trigger.definition);
            sql
        })
}


//! Column definitions, identity, foreign keys, checks and indexes as
//! `PostgreSQL` SQL, shared by `ALTER TABLE` and `CREATE TABLE`.
use super::{AlterError, data_type, default_sql, quote, relation};
use openrows_driver_api::schema::{
    Identity, IndexMethod, NewCheck, NewColumn, NewForeignKey, NewIndex, ReferentialAction,
};
use std::fmt::Write as _;

/// `GENERATED … AS IDENTITY`, or `None` for a plain column.
pub(super) fn identity(identity: Identity) -> Result<Option<&'static str>, AlterError> {
    match identity {
        Identity::None => Ok(None),
        Identity::Always => Ok(Some("GENERATED ALWAYS AS IDENTITY")),
        Identity::ByDefault => Ok(Some("GENERATED BY DEFAULT AS IDENTITY")),
        Identity::AutoIncrement => Err(AlterError::Unsupported(
            "PostgreSQL numbers rows with identity columns: choose ALWAYS or BY DEFAULT".to_owned(),
        )),
    }
}

/// ` COLLATE "name"`, `COLLATE "default"` for `None`; a character set is refused.
pub(super) fn collate(
    charset: Option<&str>,
    collation: Option<&str>,
) -> Result<String, AlterError> {
    if charset.is_some() {
        return Err(AlterError::Unsupported(
            "PostgreSQL columns have no character set; the database encoding applies".to_owned(),
        ));
    }
    Ok(format!(
        " COLLATE {}",
        quote(collation.unwrap_or("default"))?
    ))
}

/// `"name" type [COLLATE …] [GENERATED … AS IDENTITY] [NOT NULL] [DEFAULT …]`.
pub(super) fn column_definition(column: &NewColumn) -> Result<String, AlterError> {
    let mut sql = format!("{} {}", quote(&column.name)?, data_type(&column.data_type)?);
    if column.charset.is_some() || column.collation.is_some() {
        sql.push_str(&collate(
            column.charset.as_deref(),
            column.collation.as_deref(),
        )?);
    }
    let default = default_sql(&column.name, &column.default)?;
    if let Some(clause) = identity(column.identity)? {
        if default.is_some() {
            return Err(AlterError::Conflict(column.name.clone()));
        }
        sql.push(' ');
        sql.push_str(clause);
    }
    if !column.nullable {
        sql.push_str(" NOT NULL");
    }
    if let Some(default) = default {
        sql.push_str(" DEFAULT ");
        sql.push_str(&default);
    }
    Ok(sql)
}

/// `"a", "b"`.
pub(super) fn column_list(columns: &[String]) -> Result<String, AlterError> {
    Ok(columns
        .iter()
        .map(|column| quote(column))
        .collect::<Result<Vec<_>, _>>()?
        .join(", "))
}

/// `CONSTRAINT "name" ` when named.
fn constraint_name(name: Option<&str>) -> Result<String, AlterError> {
    match name.filter(|name| !name.is_empty()) {
        Some(name) => Ok(format!("CONSTRAINT {} ", quote(name)?)),
        None => Ok(String::new()),
    }
}

/// `[CONSTRAINT n] FOREIGN KEY (…) REFERENCES s.t (…) [ON DELETE …] [ON UPDATE …]`;
/// the target defaults to `schema`.
pub(super) fn foreign_key(key: &NewForeignKey, schema: &str) -> Result<String, AlterError> {
    let target_schema = Some(key.target.schema.as_str())
        .filter(|name| !name.is_empty())
        .unwrap_or(schema);
    let mut sql = format!(
        "{}FOREIGN KEY ({}) REFERENCES {} ({})",
        constraint_name(key.name.as_deref())?,
        column_list(&key.columns)?,
        relation(target_schema, &key.target.table)?,
        column_list(&key.target.columns)?
    );
    for (event, action) in [("DELETE", key.on_delete), ("UPDATE", key.on_update)] {
        if action != ReferentialAction::NoAction {
            let _ = write!(sql, " ON {event} {}", action.sql());
        }
    }
    Ok(sql)
}

/// `[CONSTRAINT n] CHECK (expression)`.
pub(super) fn check(check: &NewCheck) -> Result<String, AlterError> {
    Ok(format!(
        "{}CHECK ({})",
        constraint_name(check.name.as_deref())?,
        check.expression.trim()
    ))
}

/// `CREATE [UNIQUE] INDEX [name] ON relation USING method (keys) [WHERE …]`.
pub(super) fn create_index(relation: &str, index: &NewIndex) -> Result<String, AlterError> {
    let unique = if index.unique { "UNIQUE " } else { "" };
    let name = match index.name.as_deref().filter(|name| !name.is_empty()) {
        Some(name) => format!("{} ", quote(name)?),
        None => String::new(),
    };
    let keys = index
        .columns
        .iter()
        .map(|column| {
            let order = if index.descending.contains(column) {
                " DESC"
            } else {
                ""
            };
            quote(column).map(|quoted| format!("{quoted}{order}"))
        })
        .collect::<Result<Vec<_>, _>>()?
        .join(", ");
    let mut sql = format!(
        "CREATE {unique}INDEX {name}ON {relation} USING {} ({keys})",
        method(index.method)
    );
    if let Some(predicate) = index.predicate.as_deref().map(str::trim) {
        let _ = write!(sql, " WHERE ({predicate})");
    }
    Ok(sql)
}

fn method(method: IndexMethod) -> &'static str {
    match method {
        IndexMethod::Btree => "btree",
        IndexMethod::Hash => "hash",
        IndexMethod::Gist => "gist",
        IndexMethod::Gin => "gin",
        IndexMethod::Brin => "brin",
        IndexMethod::Spgist => "spgist",
    }
}

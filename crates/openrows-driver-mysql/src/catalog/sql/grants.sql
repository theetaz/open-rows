SELECT 'global', NULL, NULL, NULL, PRIVILEGE_TYPE, IS_GRANTABLE
FROM information_schema.USER_PRIVILEGES WHERE GRANTEE = ?
UNION ALL
SELECT 'schema', TABLE_SCHEMA, NULL, NULL, PRIVILEGE_TYPE, IS_GRANTABLE
FROM information_schema.SCHEMA_PRIVILEGES WHERE GRANTEE = ?
UNION ALL
SELECT 'table', TABLE_SCHEMA, TABLE_NAME, NULL, PRIVILEGE_TYPE, IS_GRANTABLE
FROM information_schema.TABLE_PRIVILEGES WHERE GRANTEE = ?
UNION ALL
SELECT 'column', TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, PRIVILEGE_TYPE, IS_GRANTABLE
FROM information_schema.COLUMN_PRIVILEGES WHERE GRANTEE = ?
ORDER BY 1, 2, 3, 4, 5

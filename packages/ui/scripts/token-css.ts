import {
  light,
  dark,
  highContrast,
  typography,
  geometry,
  material,
} from '../src/tokens/index.ts';

function block(selector: string, tokens: Record<string, string>): string {
  const values = Object.entries(tokens).map(
    ([key, value]) => `  --or-${key}: ${value};`,
  );
  return `${selector} {\n${values.join('\n')}\n}\n`;
}
function themed(
  lightValues: Record<string, string>,
  darkValues: Record<string, string>,
): string {
  return (
    block(':root', lightValues) +
    block('[data-theme="dark"]', darkValues) +
    `@media (prefers-color-scheme: dark) {\n${block('[data-theme="system"]', darkValues)}}\n`
  );
}
/** Deterministically generate the stylesheet exclusively from TypeScript tokens. */
export function generateCss(): string {
  return (
    '/* SPDX-License-Identifier: Apache-2.0 */\n/* Generated by just gen-tokens. */\n' +
    block(':root', { ...typography, ...geometry, ...material }) +
    themed(
      { ...light, 'color-scheme': 'light' },
      { ...dark, 'color-scheme': 'dark' },
    ) +
    `@media (prefers-contrast: more) {\n${themed(highContrast.light, highContrast.dark)}}\n` +
    block('[data-transparency="reduced"]', {
      panel: 'var(--or-panel-solid)',
      'glass-panel': 'none',
      'glass-toolbar': 'none',
      toolbar: 'var(--or-page)',
    }) +
    `@media (prefers-reduced-transparency: reduce) {\n${block(':root', { panel: 'var(--or-panel-solid)', 'glass-panel': 'none', 'glass-toolbar': 'none', toolbar: 'var(--or-page)' })}}\n` +
    `@media (prefers-reduced-motion: reduce) {\n${block(':root', { 'motion-panel': '0ms', 'motion-disclosure': '0ms' })}*, *::before, *::after { animation: none !important; transition: none !important; scroll-behavior: auto !important; }\n}\n`
  );
}

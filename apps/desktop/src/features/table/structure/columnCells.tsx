import type { ReactNode } from 'react';
import { Icon } from '@openrows/ui';
import type { ColumnRow } from './effective';
import type { CellView } from './StructureGrid';
import styles from './Structure.module.css';

/** An inline editor in progress: the cell, its text and the default mode. */
export type InlineEdit = {
  row: number;
  col: number;
  text: string;
  /** The default is a text literal, not an SQL expression. */
  literal: boolean;
};

const generatedText: Record<string, string> = {
  identityAlways: 'GENERATED ALWAYS AS IDENTITY',
  identityByDefault: 'GENERATED BY DEFAULT AS IDENTITY',
};

/** Small up/down glyph that opens a picker; keeps focus on the grid. */
function Stepper({
  label,
  onOpen,
}: {
  label: string;
  onOpen: (at: { x: number; y: number }) => void;
}): React.JSX.Element {
  return (
    <button
      type="button"
      tabIndex={-1}
      className={styles.stepper}
      aria-label={label}
      onMouseDown={(event) => {
        event.preventDefault();
      }}
      onClick={(event) => {
        const box = event.currentTarget.getBoundingClientRect();
        onOpen({ x: box.left, y: box.bottom });
      }}
    >
      <Icon name="chevronUpDown" />
    </button>
  );
}

/** The text input of an inline edit. Enter/Tab commit, Escape cancels. */
export function CellInput({
  edit,
  label,
  onText,
  onDone,
}: {
  edit: InlineEdit;
  label: string;
  onText: (text: string) => void;
  /** Enter commits, Tab commits and moves right, Escape cancels. */
  onDone: (how: 'commit' | 'cancel' | 'next' | 'blur') => void;
}): React.JSX.Element {
  return (
    <input
      className={styles.input}
      aria-label={label}
      placeholder={edit.literal ? 'Text literal' : undefined}
      value={edit.text}
      autoFocus
      spellCheck={false}
      onChange={(event) => {
        onText(event.target.value);
      }}
      onBlur={() => {
        onDone('blur');
      }}
      onKeyDown={(event) => {
        if (event.key === 'Enter' || event.key === 'Tab') {
          event.preventDefault();
          onDone(event.key === 'Tab' ? 'next' : 'commit');
        } else if (event.key === 'Escape') {
          event.preventDefault();
          onDone('cancel');
        }
      }}
    />
  );
}

function withStepper(text: ReactNode, stepper: ReactNode): React.JSX.Element {
  return (
    <span className={styles.cell}>
      <span>{text}</span>
      {stepper}
    </span>
  );
}

/** Pickers for data_type, is_nullable and column_default cells. */
type CellPickers = {
  open: (
    field: 'dataType' | 'nullable' | 'default',
    row: number,
    at: { x: number; y: number },
  ) => void;
  openTable: (row: ColumnRow) => void;
  editable: boolean;
};

/** The view of one Structure cell (`col` indexes `columnFields`). */
export function columnCell(
  row: ColumnRow,
  [index, col]: [number, number],
  pickers: CellPickers,
): CellView {
  const step = (field: 'dataType' | 'nullable' | 'default'): ReactNode =>
    pickers.editable && !row.dropped ? (
      <Stepper
        label={`Choose ${field === 'dataType' ? 'type' : field} of ${row.name}`}
        onOpen={(at) => {
          pickers.open(field, index, at);
        }}
      />
    ) : null;
  const changed = (field: string): boolean =>
    (row.changed as readonly string[]).includes(field) && row.column !== null;
  switch (col) {
    case 0:
      return { content: index + 1 };
    case 1:
      return { content: row.name, changed: changed('name') };
    case 2:
      return {
        content: withStepper(row.dataType, step('dataType')),
        changed: changed('dataType'),
      };
    case 3:
      return {
        content: withStepper(row.nullable ? 'YES' : 'NO', step('nullable')),
        changed: changed('nullable'),
      };
    case 4:
      return { content: row.check ?? 'NULL', muted: row.check === null };
    case 5:
      return defaultCell(row, step('default'), changed('default'));
    case 6:
      return foreignKeyCell(row, pickers);
    default:
      return {
        content: row.comment ?? 'NULL',
        muted: row.comment === null,
        changed: changed('comment'),
      };
  }
}

function defaultCell(
  row: ColumnRow,
  stepper: ReactNode,
  changed: boolean,
): CellView {
  const generated = generatedText[row.generated];
  if (generated) return { content: generated, muted: true };
  const text =
    row.generated === 'stored' && row.default !== null
      ? `GENERATED ALWAYS AS (${row.default}) STORED`
      : row.default;
  return {
    content: withStepper(
      text ?? 'NULL',
      row.generated === 'no' ? stepper : null,
    ),
    muted: text === null,
    changed,
  };
}

function foreignKeyCell(row: ColumnRow, pickers: CellPickers): CellView {
  const key = row.foreignKey;
  if (!key) return { content: 'EMPTY', muted: true };
  return {
    content: (
      <span className={styles.cell}>
        <span>{`${key.table}(${key.column})`}</span>
        <button
          type="button"
          tabIndex={-1}
          className={styles.stepper}
          aria-label={`Open ${key.schema}.${key.table}`}
          title={`Open ${key.schema}.${key.table}`}
          onMouseDown={(event) => {
            event.preventDefault();
          }}
          onClick={() => {
            pickers.openTable(row);
          }}
        >
          <Icon name="arrowRight" />
        </button>
      </span>
    ),
  };
}
